-- Виправляє недолік попередньої міграції (checkin-local-date-timezone-fix-
-- migration.sql): її бекфіл заповнював local_date через `created_at::date`
-- (UTC) — тобто те саме значення, яке й було джерелом бага, тож для вже
-- існуючих на момент тієї міграції рядків нічого фактично не виправляв.
--
-- Тут бекфіл рахує через `created_at AT TIME ZONE 'Europe/Kyiv'` — набагато
-- точніше наближення справжньої локальної дати автора для цього застосунку
-- (аудиторія переважно українська), ніж голий UTC-каст. Перезаписує local_date
-- для ВСІХ рядків, включно з уже заповненими попереднім (неправильним)
-- бекфілом — це безпечно зараз, бо переважна більшість наявних чек-інів була
-- створена до того, як клієнт почав сам надсилати правильну локальну дату.
--
-- Ідемпотентно, безпечно виконувати повторно.

update public.checkins
  set local_date = (created_at at time zone 'Europe/Kyiv')::date;

update public.subject_checkins
  set local_date = (created_at at time zone 'Europe/Kyiv')::date;
